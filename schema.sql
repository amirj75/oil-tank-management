create table if not exists public.tanks (
  id bigint generated by default as identity primary key,
  name text not null unique,
  capacity_l numeric(12,2) not null check (capacity_l > 0),
  stock_l numeric(12,2) not null default 0 check (stock_l >= 0 and stock_l <= capacity_l)
);

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  tank_id bigint not null references public.tanks(id),
  tank_name text not null,
  type text not null check (type in ('in','out')),
  amount_l numeric(12,2) not null check (amount_l > 0),
  operator text,
  equipment text,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id)
);

