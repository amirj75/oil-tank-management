alter table public.tanks enable row level security;
alter table public.transactions enable row level security;

create policy "authenticated can read tanks" on public.tanks for select to authenticated using (true);
create policy "authenticated can read transactions" on public.transactions for select to authenticated using (true);

create or replace function public.record_stock_transaction(
  p_tank_id bigint, p_type text, p_amount_l numeric,
  p_operator text default null, p_equipment text default null
) returns void language plpgsql security definer set search_path=public
as $$
declare t public.tanks%rowtype;
begin
  if auth.uid() is null then raise exception 'unauthorized'; end if;
  select * into t from public.tanks where id=p_tank_id for update;
  if not found then raise exception 'tank not found'; end if;
  if p_amount_l <= 0 then raise exception 'amount must be positive'; end if;
  if p_type='in' then
    if t.stock_l+p_amount_l>t.capacity_l then raise exception 'capacity exceeded'; end if;
    update public.tanks set stock_l=stock_l+p_amount_l where id=p_tank_id;
  elsif p_type='out' then
    if t.stock_l<p_amount_l then raise exception 'insufficient stock'; end if;
    update public.tanks set stock_l=stock_l-p_amount_l where id=p_tank_id;
  else raise exception 'invalid transaction type'; end if;
  insert into public.transactions(tank_id,tank_name,type,amount_l,operator,equipment,created_by)
  values(t.id,t.name,p_type,p_amount_l,p_operator,p_equipment,auth.uid());
end $$;

grant execute on function public.record_stock_transaction(bigint,text,numeric,text,text) to authenticated;
